// Obter edição atual (mais recente)
export const getEdicaoAtual = () => periodicos[0];

// Obter edições anteriores
export const getEdicoesAnteriores = () => periodicos.slice(1);

// Buscar periódico por ID
export const getPeriodicoById = (id) => periodicos.find(p => p.id === id);

// Buscar periódicos por ano
export const getPeriodicosPorAno = (ano) => periodicos.filter(p => p.ano === ano);

// Obter anos disponíveis
export const getAnosDisponiveis = () => {
  const anos = [...new Set(periodicos.map(p => p.ano))];
  return anos.sort((a, b) => b - a); // Ordena do mais recente para o mais antigo
};

